def emit():
    lines = []
    for d, pn, x, y, o, m in PLACE:
        e = db[pn]
        lines.append(f"PART|{d}|{e['lib']}|{e['symbol']}|{pn}|{x}|{y}|{o}|{m}")
        lines.append(f"COMMENT|{e['symbol']}")
        if e["footprint"]:
            lines.append(f"FOOTPRINT|{e['footprint']}")
        if e["desc"]:
            lines.append(f"DESCRIPTION|{e['desc']}")
        for k, v in e["params"].items():
            lines.append(f"PARAM|{k}|{v}")
    for w in W:
        lines.append("WIRE|" + "|".join(str(v) for v in w))
    for x, y in J:
        lines.append(f"JUNCTION|{x}|{y}")
    for x, y, t in L:
        lines.append(f"NETLABEL|{x}|{y}|0|{t}")
    for x, y in GND:
        lines.append(f"POWER|{x}|{y}|3|5|GND|0")
    lines.extend(SPORTS)
    lines.append("NOTE|1100|6600|Power entry and rails - rebuilt from the reference circuit by connectivity only")
    (EX / "circuit_spec.txt").write_text("\n".join(lines) + "\n",
                                        encoding="cp1252", errors="replace")
    return len(lines)


def run_bridge():
    prj = str((pathlib.Path(__file__).resolve().parent.parent /
               "server/AltiumScript/Altium_API.PrjScr").resolve())
    resp = EX / "response.json"
    if resp.exists():
        resp.unlink()
    (EX / "request.json").write_text(json.dumps(
        {"command": "build_circuit", "parameters": {}}, indent=2))
    cmd = (f'"{altium_exe()}" -RScriptingSystem:RunScript(ProjectName="{prj}"'
           f'^|ProcName="Altium_API>Run")')
    subprocess.Popen(cmd, shell=True)
    for _ in range(240):
        if resp.exists():
            return resp.read_text()
        time.sleep(1)
    return "TIMEOUT"


if __name__ == "__main__":
    print("spec lines:", emit())
    print(run_bridge()[:300])
